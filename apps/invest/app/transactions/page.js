'use client'

import { useMemo, useState } from 'react'
import { useRouter } from 'next/navigation'
import { ArrowLeftRight, ShoppingCart, BadgeIndianRupee, Coins } from 'lucide-react'
import { KPICard, useTableSort } from '@webfudge/ui'
import { useInvest } from '../../components/InvestDataProvider'
import InvestPageHeader from '../../components/InvestPageHeader'
import TransactionModal from '../../components/TransactionModal'
import { Page, TypeBadge, KindBadge, ErrorBanner, ListView, FilterModal, RowActions, ConfirmDeleteModal, num, downloadCsv, KPI_GRID } from '../../components/ui'
import { investApi } from '../../lib/api'
import { formatINR, formatINRCompact, formatPrice, formatUnits, formatDate, TYPE_LABELS, KIND_LABELS } from '../../lib/format'

const TABS = [
  { key: 'all', label: 'All' },
  { key: 'buy', label: 'Buys' },
  { key: 'sell', label: 'Sells' },
  { key: 'sip', label: 'SIP instalments' },
  { key: 'dividend', label: 'Dividends' },
]

const SORT_COLUMNS = [
  { key: 'date', label: 'Date' },
  { key: 'type', label: 'Type' },
  { key: 'instrument', label: 'Instrument' },
  { key: 'units', label: 'Units' },
  { key: 'price', label: 'Price' },
  { key: 'amount', label: 'Amount' },
  { key: 'charges', label: 'Charges' },
  { key: 'account', label: 'Account' },
]

function relId(rel) {
  return rel && typeof rel === 'object' ? rel.id : rel
}

function sumAmount(list, type) {
  return list.filter((t) => t.type === type).reduce((s, t) => s + (Number(t.amount) || 0), 0)
}

export default function TransactionsPage() {
  const router = useRouter()
  const { loading, error, transactions, reload } = useInvest()
  const [tab, setTab] = useState('all')
  const [q, setQ] = useState('')
  const [filters, setFilters] = useState({})
  const [filterOpen, setFilterOpen] = useState(false)
  const [modal, setModal] = useState({ open: false, tx: null })
  const [toDelete, setToDelete] = useState(null)
  const sort = useTableSort({ storageKey: 'invest-transactions-sort', defaultRules: [{ key: 'date', direction: 'desc' }] })

  const accounts = useMemo(() => [...new Set(transactions.map((t) => t.account).filter(Boolean))].sort(), [transactions])

  const filtered = useMemo(() => {
    const term = q.trim().toLowerCase()
    return transactions.filter(
      (t) =>
        (!filters.kind || t.instrument?.kind === filters.kind) &&
        (!filters.account || t.account === filters.account) &&
        (!filters.from || String(t.date) >= filters.from) &&
        (!filters.to || String(t.date) <= filters.to) &&
        (!filters.origin || (filters.origin === 'auto' ? t.autoGenerated : !t.autoGenerated)) &&
        (!term || `${t.instrument?.name || ''} ${t.instrument?.symbol || ''} ${t.account || ''} ${t.folio || ''} ${t.notes || ''}`.toLowerCase().includes(term))
    )
  }, [transactions, filters, q])

  const rows = useMemo(
    () =>
      sort.sortData(
        filtered.filter((t) => tab === 'all' || t.type === tab),
        (t, key) => (key === 'instrument' ? (t.instrument?.name || '').toLowerCase() : key === 'date' ? String(t.date) : t[key])
      ),
    [filtered, tab, sort]
  )
  const counts = useMemo(() => Object.fromEntries(TABS.map((t) => [t.key, t.key === 'all' ? filtered.length : filtered.filter((x) => x.type === t.key).length])), [filtered])

  const bought = sumAmount(filtered, 'buy')
  const sipped = sumAmount(filtered, 'sip')
  const sold = sumAmount(filtered, 'sell')
  const divs = sumAmount(filtered, 'dividend')

  const columns = [
    { key: 'date', label: 'Date', className: 'whitespace-nowrap', render: (v) => formatDate(v) },
    { key: 'type', label: 'Type', render: (v) => <TypeBadge type={v} /> },
    {
      key: 'instrument',
      label: 'Instrument',
      render: (_, t) => (
        <div className="min-w-0 max-w-[16rem]">
          <p className="truncate font-medium text-gray-900">{t.instrument?.name}</p>
          <span className="inline-flex items-center gap-2">
            <KindBadge kind={t.instrument?.kind} />
            {t.autoGenerated ? <span className="text-xs text-gray-400">auto</span> : null}
          </span>
        </div>
      ),
    },
    num({ key: 'units', label: 'Units', render: (v) => (v ? formatUnits(v) : '—') }),
    num({ key: 'price', label: 'Price', render: (v) => (v ? formatPrice(v) : '—') }),
    num({ key: 'amount', label: 'Amount', render: (v) => formatINR(v, { decimals: 2 }) }),
    num({ key: 'charges', label: 'Charges', render: (v) => (v ? formatINR(v, { decimals: 2 }) : '—') }),
    { key: 'account', label: 'Account', render: (v) => <span className="text-gray-600">{v || '—'}</span> },
    {
      key: 'actions',
      label: 'Actions',
      headerClassName: 'text-right',
      className: 'text-right',
      render: (_, t) => (
        <RowActions
          onView={() => router.push(`/holdings/${relId(t.instrument)}`)}
          onEdit={() => setModal({ open: true, tx: t })}
          onDelete={() => setToDelete(t)}
        />
      ),
    },
  ]

  function exportCsv() {
    downloadCsv(
      `webfudge-transactions-${new Date().toISOString().slice(0, 10)}.csv`,
      ['Date', 'Type', 'Instrument', 'Symbol/Scheme', 'Units', 'Price', 'Amount', 'Charges', 'Account', 'Folio', 'Notes'],
      rows.map((t) => [t.date, TYPE_LABELS[t.type], t.instrument?.name, t.instrument?.symbol || t.instrument?.schemeCode, t.units, t.price, t.amount, t.charges, t.account, t.folio, t.notes])
    )
  }

  return (
    <Page>
      <InvestPageHeader
        title="Transactions"
        subtitle="Every buy, sell, SIP instalment and dividend"
        breadcrumb={[
          { label: 'Portfolio', href: '/' },
          { label: 'Transactions', href: '/transactions' },
        ]}
        showActions
        onExportClick={exportCsv}
      />

      <div className={KPI_GRID}>
        <KPICard title="Put In" value={formatINRCompact(bought + sipped)} valueTitle={formatINR(bought + sipped)} subtitle={`${counts.buy} buys · ${counts.sip} SIP instalments`} icon={ShoppingCart} colorScheme="orange" />
        <KPICard title="Sold" value={formatINRCompact(sold)} valueTitle={formatINR(sold)} subtitle={`${counts.sell} sells`} icon={BadgeIndianRupee} colorScheme="orange" />
        <KPICard title="Dividends" value={formatINRCompact(divs)} valueTitle={formatINR(divs)} subtitle={`${counts.dividend} payouts`} icon={Coins} colorScheme="orange" />
      </div>

      <ErrorBanner message={error} />

      <ListView
        tabs={TABS.map((t) => ({ key: t.key, label: t.label, badge: String(counts[t.key] || 0) }))}
        activeTab={tab}
        onTabChange={setTab}
        searchQuery={q}
        onSearchChange={setQ}
        searchPlaceholder="Search instrument, broker, notes..."
        onAddClick={() => setModal({ open: true, tx: null })}
        addTitle="Add transaction"
        onFilterClick={() => setFilterOpen(true)}
        sort={sort}
        sortColumnOptions={SORT_COLUMNS}
        columns={columns}
        rows={rows}
        loading={loading}
        onRowClick={(t) => setModal({ open: true, tx: t })}
        empty={{
          icon: ArrowLeftRight,
          title: 'No transactions found',
          description: transactions.length ? 'Try adjusting your filters' : 'Record a buy, SIP instalment or dividend to start the portfolio',
        }}
      />

      <FilterModal
        isOpen={filterOpen}
        onClose={() => setFilterOpen(false)}
        title="Filter Transactions"
        description="Refine your transaction list"
        value={filters}
        onApply={setFilters}
        fields={[
          { key: 'kind', label: 'Instrument type', options: Object.entries(KIND_LABELS).map(([value, label]) => ({ value, label })) },
          { key: 'account', label: 'Broker / account', options: accounts.map((a) => ({ value: a, label: a })) },
          { key: 'from', label: 'From date', type: 'date' },
          { key: 'to', label: 'To date', type: 'date' },
          { key: 'origin', label: 'Entered by', options: [{ value: 'manual', label: 'Entered by hand' }, { value: 'auto', label: 'Auto-recorded SIP' }] },
        ]}
      />

      <TransactionModal isOpen={modal.open} transaction={modal.tx} onClose={() => setModal({ open: false, tx: null })} />
      <ConfirmDeleteModal
        isOpen={Boolean(toDelete)}
        title="Delete Transaction"
        confirmLabel="Delete Transaction"
        message={toDelete ? `Delete this ${TYPE_LABELS[toDelete.type].toLowerCase()} of ${formatINR(toDelete.amount)} in ${toDelete.instrument?.name} on ${formatDate(toDelete.date)}?` : ''}
        onConfirm={async () => {
          await investApi.deleteTransaction(toDelete.id)
          await reload()
        }}
        onClose={() => setToDelete(null)}
      />
    </Page>
  )
}
